"""Keep one version everywhere, and the agent manifests in step with the plugin.

pyproject.toml holds the version. This script stamps it into the package, the Claude Code
plugin and marketplace manifests, and the Gemini CLI extension, pins the install commands in
the plugin, README and doctor to the version's tag, and regenerates the Gemini extension
(manifest and context file) from the plugin's .mcp.json and skill.

    uv run scripts/sync_version.py                # write
    uv run scripts/sync_version.py --check        # exit 1 if anything is out of date
    uv run scripts/sync_version.py --check --tag v0.2.0
                                                  # also: tag matches, CHANGELOG.md has a dated section
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "claude-plugin"
SKILL = PLUGIN / "skills" / "showntell" / "SKILL.md"
VERSION_KEY = re.compile(r'("version"\s*:\s*")[^"]*(")')
DUNDER = re.compile(r'(__version__\s*=\s*")[^"]*(")')
# Installs from GitHub are pinned to the version's tag until showntell is on PyPI.
REPO = "git+https://github.com/rahimnathwani/showntell"
PINNED = re.compile(re.escape(REPO) + r"(?:@v\d[\w.]*)?")


def pyproject_version() -> str:
    return tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]


def _stamp(text: str, pattern: re.Pattern, version: str, path: Path) -> str:
    out, n = pattern.subn(lambda m: m.group(1) + version + m.group(2), text)
    if n != 1:
        raise SystemExit(f"{path.relative_to(ROOT)}: expected one version field, found {n}")
    return out


def _pin(text: str, version: str, path: Path) -> str:
    out, n = PINNED.subn(f"{REPO}@v{version}", text)
    if not n:
        raise SystemExit(f"{path.relative_to(ROOT)}: expected an install from {REPO}")
    return out


def gemini_context() -> str:
    """The plugin skill for Gemini CLI's context file: the front matter's description, which says
    when to use it, becomes the first paragraph under the title."""
    front, body = SKILL.read_text().split("\n---\n", 1)
    desc = next(ln.split(":", 1)[1].strip() for ln in front.splitlines() if ln.startswith("description:"))
    title, rest = body.lstrip("\n").split("\n", 1)
    note = "<!-- Generated by scripts/sync_version.py from claude-plugin/skills/showntell/SKILL.md. Edit that file. -->"
    return f"{note}\n\n{title}\n\n{desc}\n{rest}"


def gemini_manifest(version: str) -> str:
    plugin = json.loads((PLUGIN / ".claude-plugin" / "plugin.json").read_text())
    mcp = json.loads((PLUGIN / ".mcp.json").read_text())
    manifest = {
        "name": plugin["name"],
        "version": version,
        "description": plugin["description"],
        "contextFileName": "GEMINI.md",
        "mcpServers": mcp["mcpServers"],
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def expected() -> dict[Path, str]:
    """Every generated or stamped file, with the content it should have."""
    v = pyproject_version()
    files: dict[Path, str] = {}
    for path, pattern in [
        (ROOT / "src" / "showntell" / "__init__.py", DUNDER),
        (PLUGIN / ".claude-plugin" / "plugin.json", VERSION_KEY),
        (ROOT / ".claude-plugin" / "marketplace.json", VERSION_KEY),
    ]:
        files[path] = _stamp(path.read_text(), pattern, v, path)
    for path in (PLUGIN / ".mcp.json", ROOT / "README.md", ROOT / "src" / "showntell" / "doctor.py"):
        files[path] = _pin(path.read_text(), v, path)
    files[ROOT / "gemini-extension.json"] = gemini_manifest(v)
    files[ROOT / "GEMINI.md"] = gemini_context()
    return files


def drift() -> list[str]:
    """Paths, relative to the repo, whose content differs from what this script would write."""
    return [str(p.relative_to(ROOT)) for p, want in expected().items() if not p.is_file() or p.read_text() != want]


def changelog_problem(version: str) -> str | None:
    """None when CHANGELOG.md has a released (not 'unreleased') section for version with some text."""
    text = (ROOT / "CHANGELOG.md").read_text()
    m = re.search(rf"^## {re.escape(version)}\b(.*)$", text, re.M)
    if not m:
        return f"CHANGELOG.md has no '## {version}' section"
    if "unreleased" in m.group(1).lower():
        return f"CHANGELOG.md still marks {version} as unreleased; replace that with the release date"
    body = text[m.end() :]
    nxt = re.search(r"^## ", body, re.M)
    if not (body[: nxt.start()] if nxt else body).strip():
        return f"CHANGELOG.md's {version} section is empty"
    return None


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report drift instead of writing")
    ap.add_argument("--tag", help="release tag, such as v0.2.0, to check against pyproject.toml and CHANGELOG.md")
    args = ap.parse_args()
    version = pyproject_version()
    problems: list[str] = []
    if args.check:
        problems += [f"{p} is out of date; run `uv run scripts/sync_version.py`" for p in drift()]
    else:
        for path, content in expected().items():
            if not path.is_file() or path.read_text() != content:
                path.write_text(content)
                print(f"wrote {path.relative_to(ROOT)}")
    if args.tag:
        if args.tag != f"v{version}":
            problems.append(f"tag {args.tag} does not match pyproject.toml version {version} (expected v{version})")
        if problem := changelog_problem(version):
            problems.append(problem)
    for p in problems:
        print(p, file=sys.stderr)
    if problems:
        sys.exit(1)
    print(f"showntell {version}: manifests in sync")


if __name__ == "__main__":
    main()
